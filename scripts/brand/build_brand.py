"""Builds every brand asset from the supplied artwork (scripts/brand/sellandiamman-logo-source.png).

The artwork is traced once into vector outlines (grey S, yellow A, white SELLANDIAMMAN wordmark), then written out:
  frontend/src/components/brand/paths.js       outlines used by <Mark/> and <Logo/>
  backend/brand.py                             the same outlines as polygons for the PDF letterhead
  frontend/public/favicon.svg, icon-192.png, icon-512.png, apple-touch-icon.png, og-image.jpg
  frontend/public/brand/*.svg / *.png          mark and lockups for dark and light backgrounds

Run from the repository root:  python scripts/brand/build_brand.py   (needs opencv-python-headless, numpy, pillow, playwright)
"""
import asyncio
import json
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "scripts/brand/sellandiamman-logo-source.png"
PUBLIC = ROOT / "frontend/public"
UP = 4
COLORS = {"dark": {"s": "#A9ADB3", "a": "#FFC400", "word": "#FFFFFF", "sub": "#A9ADB3"},
          "light": {"s": "#80858C", "a": "#F2B300", "word": "#0A1626", "sub": "#5B6472"}}
INK = "#0A1626"


def masks():
    im = cv2.imread(str(SRC)).astype(np.float32)
    im = cv2.resize(im, None, fx=UP, fy=UP, interpolation=cv2.INTER_CUBIC)
    b, g, r = im[:, :, 0], im[:, :, 1], im[:, :, 2]
    lum = (r + g + b) / 3
    yellow = ((r - b > 110) & (g - b > 70)).astype(np.uint8)
    grey = ((lum > 95) & (np.abs(r - b) < 40) & (lum < 225)).astype(np.uint8)
    white = (lum > 150).astype(np.uint8)
    cut = 600 * UP
    yellow[cut:] = 0
    grey[cut:] = 0
    white[:cut] = 0
    grey[yellow > 0] = 0
    k = np.ones((5, 5), np.uint8)
    out = {}
    for name, m in (("s", grey), ("a", yellow), ("word", white)):
        m = cv2.morphologyEx(m, cv2.MORPH_OPEN, k)
        m = cv2.GaussianBlur(m.astype(np.float32), (9, 9), 0)
        out[name] = (m > 0.5).astype(np.uint8)
    return out


def polys(mask, eps):
    cs, hier = cv2.findContours(mask * 255, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    out = []
    for c in cs:
        if cv2.contourArea(c) < 150 * UP * UP / 4:
            continue
        ap = cv2.approxPolyDP(c, eps, True).reshape(-1, 2).astype(float) / UP
        out.append(ap)
    return out


def path_d(ps, ox, oy):
    d = []
    for p in ps:
        pts = [f"{x - ox:.1f} {y - oy:.1f}" for x, y in p]
        d.append("M" + " L".join(pts) + "Z")
    return "".join(d)


def main():
    m = masks()
    P = {k: polys(v, 1.6 if k != "word" else 1.2) for k, v in m.items()}
    allm = np.vstack([np.vstack(P["s"]), np.vstack(P["a"])])
    mx0, my0 = allm.min(0)
    mx1, my1 = allm.max(0)
    w_all = np.vstack(P["word"])
    wx0, wy0 = w_all.min(0)
    wx1, wy1 = w_all.max(0)
    mark = {"w": round(mx1 - mx0, 1), "h": round(my1 - my0, 1), "s": path_d(P["s"], mx0, my0), "a": path_d(P["a"], mx0, my0)}
    word = {"w": round(wx1 - wx0, 1), "h": round(wy1 - wy0, 1), "d": path_d(P["word"], wx0, wy0)}
    js = ("// Generated by scripts/brand/build_brand.py from the supplied artwork — do not edit by hand.\n"
          f"export const MARK = {json.dumps(mark)};\nexport const WORD = {json.dumps(word)};\nexport const COLORS = {json.dumps(COLORS)};\n")
    (ROOT / "frontend/src/components/brand").mkdir(parents=True, exist_ok=True)
    (ROOT / "frontend/src/components/brand/paths.js").write_text(js)
    # PDF polygons (y up), normalised to mark height 1
    def norm(ps):
        return [[[round((x - mx0) / mark["h"], 4), round(1 - (y - my0) / mark["h"], 4)] for x, y in p] for p in ps]
    py = ("# Generated by scripts/brand/build_brand.py — do not edit by hand.\n"
          "from reportlab.lib import colors\n\n"
          f"MARK_ASPECT = {mark['w'] / mark['h']:.4f}\nS_POLYS = {json.dumps(norm(P['s']))}\nA_POLYS = {json.dumps(norm(P['a']))}\n\n\n"
          "def _draw(c, polys, x, y, h):\n"
          "    p = c.beginPath()\n"
          "    for poly in polys:\n"
          "        p.moveTo(x + poly[0][0] * h, y + poly[0][1] * h)\n"
          "        for px, py in poly[1:]:\n"
          "            p.lineTo(x + px * h, y + py * h)\n"
          "        p.close()\n"
          "    c.drawPath(p, stroke=0, fill=1, fillMode=0)\n\n\n"
          "def draw_mark(c, x, y, h):\n"
          "    c.saveState()\n"
          f"    c.setFillColor(colors.HexColor('{COLORS['light']['s']}'))\n"
          "    _draw(c, S_POLYS, x, y, h)\n"
          f"    c.setFillColor(colors.HexColor('{COLORS['light']['a']}'))\n"
          "    _draw(c, A_POLYS, x, y, h)\n"
          "    c.restoreState()\n")
    (ROOT / "backend/brand.py").write_text(py)
    # SVG files
    (PUBLIC / "brand").mkdir(parents=True, exist_ok=True)

    def mark_svg(theme, size=None, pad=0, bg=None, radius=0):
        W, H = mark["w"] + pad * 2, mark["h"] + pad * 2
        c = COLORS[theme]
        rect = f'<rect width="{W}" height="{H}" rx="{radius}" fill="{bg}"/>' if bg else ""
        dims = f' width="{size}" height="{size * H / W:.0f}"' if size else ""
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}"{dims} role="img" aria-label="Sellandiamman">{rect}'
                f'<g transform="translate({pad} {pad})"><path fill="{c["s"]}" fill-rule="evenodd" d="{mark["s"]}"/><path fill="{c["a"]}" fill-rule="evenodd" d="{mark["a"]}"/></g></svg>')

    def lockup_svg(theme, bg=None):
        c = COLORS[theme]
        scale = mark["w"] * 1.28 / word["w"]
        gap = mark["h"] * 0.22
        W = max(mark["w"] * 1.28, mark["w"]) + 40
        H = 20 + mark["h"] + gap + word["h"] * scale + 84
        mx = (W - mark["w"]) / 2
        wx = (W - word["w"] * scale) / 2
        rect = f'<rect width="{W:.0f}" height="{H:.0f}" fill="{bg}"/>' if bg else ""
        sub_y = 20 + mark["h"] + gap + word["h"] * scale + 58
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:.0f} {H:.0f}" role="img" aria-label="Sellandiamman Power Infra">{rect}'
                f'<g transform="translate({mx:.1f} 20)"><path fill="{c["s"]}" fill-rule="evenodd" d="{mark["s"]}"/><path fill="{c["a"]}" fill-rule="evenodd" d="{mark["a"]}"/></g>'
                f'<g transform="translate({wx:.1f} {20 + mark["h"] + gap:.1f}) scale({scale:.4f})"><path fill="{c["word"]}" fill-rule="evenodd" d="{word["d"]}"/></g>'
                f'<text x="{W / 2:.0f}" y="{sub_y:.0f}" text-anchor="middle" font-family="Montserrat, Arial, sans-serif" font-weight="700" font-size="46" letter-spacing="14" fill="{c["sub"]}">POWER INFRA</text></svg>')

    (PUBLIC / "brand/mark-dark.svg").write_text(mark_svg("dark"))
    (PUBLIC / "brand/mark-light.svg").write_text(mark_svg("light"))
    (PUBLIC / "brand/logo-dark.svg").write_text(lockup_svg("dark", INK))
    (PUBLIC / "brand/logo-light.svg").write_text(lockup_svg("light", "#FFFFFF"))
    fav = mark_svg("dark", pad=mark["w"] * 0.12, bg=INK, radius=mark["w"] * 0.18)
    (PUBLIC / "favicon.svg").write_text(fav)
    asyncio.run(render_pngs(fav, lockup_svg("dark", INK), mark_svg("dark")))
    print("mark", mark["w"], "x", mark["h"], "word", word["w"], "x", word["h"])


async def render_pngs(fav, lockup, mark_dark):
    from playwright.async_api import async_playwright
    async with async_playwright() as p:
        b = await p.chromium.launch()
        page = await b.new_page(device_scale_factor=1)
        for size, name in ((192, "icon-192.png"), (512, "icon-512.png"), (180, "apple-touch-icon.png")):
            await page.set_viewport_size({"width": size, "height": size})
            await page.set_content(f'<html><body style="margin:0">{fav.replace("<svg ", f"<svg width=\"{size}\" height=\"{size}\" ", 1)}</body></html>')
            await page.screenshot(path=str(PUBLIC / name), omit_background=False)
        await page.set_viewport_size({"width": 600, "height": 420})
        await page.set_content(f'<html><body style="margin:0;background:#0A1626">{lockup.replace("<svg ", "<svg width=\"600\" ", 1)}</body></html>')
        await page.screenshot(path=str(PUBLIC / "brand/logo-dark.png"))
        html = f"""<html><head><style>body{{margin:0;width:1200px;height:630px;background:#0A1626;font-family:Montserrat,Arial,sans-serif;color:#fff;position:relative;overflow:hidden}}
        .m{{position:absolute;left:84px;top:96px;width:260px}} h1{{position:absolute;left:84px;top:300px;margin:0;font-size:64px;line-height:1.05;letter-spacing:-1.5px;font-weight:800;width:880px}}
        p{{position:absolute;left:86px;top:470px;font-size:28px;color:#A9ADB3;margin:0}} .line{{position:absolute;left:0;right:0;bottom:64px;height:6px;background:#FFC400}}</style></head>
        <body><div class="m">{mark_dark.replace('<svg ', '<svg width="260" ', 1)}</div><h1>Power infrastructure, engineered and energised.</h1>
        <p>Sellandiamman Power Infra · LT &amp; HT electrical contracting</p><div class="line"></div></body></html>"""
        await page.set_viewport_size({"width": 1200, "height": 630})
        await page.set_content(html)
        await page.screenshot(path=str(PUBLIC / "og-image.jpg"), type="jpeg", quality=86)
        await b.close()


if __name__ == "__main__":
    main()
