    doc.meta([("Invoice no.", "SPI/ERD/INV/26-27/0001"), ...])
    doc.table(["#", "Description", "Amount"], rows, widths=[...], align=[...])
    doc.totals([("Subtotal", 1000), ("GST", 180), ("Total", 1180)])
    pdf_bytes = doc.build()
