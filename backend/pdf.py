import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import mm
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.lib.styles import ParagraphStyle
from reportlab.platypus import (BaseDocTemplate, PageTemplate, Frame, Paragraph, Spacer, Table, TableStyle, KeepTogether,
                                Image as RLImage)

try:
    import brand as BRAND
except ImportError:  # brand.py is generated by scripts/brand/build_brand.py
    BRAND = None

INK = colors.HexColor("#0E1726")
MUTED = colors.HexColor("#5B6577")
LINE = colors.HexColor("#D9DEE7")
ACCENT = colors.HexColor("#F5B800")
WASH = colors.HexColor("#F4F6F9")

S = {
    "title": ParagraphStyle("t", fontName="Helvetica-Bold", fontSize=15, leading=19, textColor=INK, spaceAfter=2),
    "sub": ParagraphStyle("s", fontName="Helvetica", fontSize=9, leading=12, textColor=MUTED),
    "h": ParagraphStyle("h", fontName="Helvetica-Bold", fontSize=10.5, leading=14, textColor=INK, spaceBefore=8, spaceAfter=4),
    "p": ParagraphStyle("p", fontName="Helvetica", fontSize=9, leading=12.5, textColor=INK),
    "small": ParagraphStyle("sm", fontName="Helvetica", fontSize=7.5, leading=10, textColor=MUTED),
    "cell": ParagraphStyle("c", fontName="Helvetica", fontSize=8.2, leading=10.5, textColor=INK),
    "cellb": ParagraphStyle("cb", fontName="Helvetica-Bold", fontSize=8.2, leading=10.5, textColor=INK),
    "cellr": ParagraphStyle("cr", fontName="Helvetica", fontSize=8.2, leading=10.5, textColor=INK, alignment=2),
    "head": ParagraphStyle("hd", fontName="Helvetica-Bold", fontSize=7.8, leading=10, textColor=colors.white),
    "headr": ParagraphStyle("hdr", fontName="Helvetica-Bold", fontSize=7.8, leading=10, textColor=colors.white, alignment=2),
}


def ind(x, d=2):
    """Indian digit grouping: 12,34,567.89"""
    if x is None or x == "":
        return ""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return str(x)
    neg = v < 0
    s = f"{abs(v):.{d}f}"
    whole, _, frac = s.partition(".")
    if len(whole) > 3:
        head, tail = whole[:-3], whole[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        whole = ",".join(parts + [tail])
    return ("-" if neg else "") + whole + ("." + frac if frac else "")


def rs(x, d=2):
    return "Rs. " + ind(x, d) if x not in (None, "") else ""


def P(text, style="p"):
    return Paragraph(escape(str(text if text is not None else "")).replace("\n", "<br/>"), S[style])


def words_inr(n):
    """Rupees in words (Indian system) for invoices."""
    n = int(round(float(n or 0)))
    ones = "Zero One Two Three Four Five Six Seven Eight Nine Ten Eleven Twelve Thirteen Fourteen Fifteen Sixteen Seventeen Eighteen Nineteen".split()
    tens = "Zero Ten Twenty Thirty Forty Fifty Sixty Seventy Eighty Ninety".split()

    def two(x):
        return ones[x] if x < 20 else tens[x // 10] + ("" if x % 10 == 0 else " " + ones[x % 10])

    def three(x):
        h, r = divmod(x, 100)
        return (ones[h] + " Hundred" + (" and " if r else "") if h else "") + (two(r) if r or not h else "")

    if n == 0:
        return "Rupees Zero Only"
    parts = []
    for name, size in (("Crore", 10 ** 7), ("Lakh", 10 ** 5), ("Thousand", 1000)):
        q, n = divmod(n, size)
        if q:
            parts.append(f"{three(q) if q < 1000 else words_inr(q).replace('Rupees ', '').replace(' Only', '')} {name}")
    if n:
        parts.append(three(n))
    return "Rupees " + " ".join(parts) + " Only"


class Letterhead:
    def __init__(self, title, settings=None, subtitle=None, landscape_mode=False, watermark=None):
        self.title = title
        self.subtitle = subtitle
        self.s = settings or {}
        self.flow = []
        self.pagesize = landscape(A4) if landscape_mode else A4
        self.watermark = watermark

    # ---------------------------------------------------------------- page furniture
    def _draw_logo(self, c, x, y, h):
        if BRAND and getattr(BRAND, "draw_mark", None):
            BRAND.draw_mark(c, x, y, h)
            return h * BRAND.MARK_ASPECT
        c.setFillColor(INK)
        c.setFont("Helvetica-Bold", h * 0.8)
        c.drawString(x, y + h * 0.15, "SA")
        return h * 1.4

    def _page(self, c, doc):
        w, h = self.pagesize
        c.saveState()
        top = h - 14 * mm
        lw = self._draw_logo(c, 15 * mm, top - 9 * mm, 11 * mm)
        name = self.s.get("company_name") or "Sellandiamman Power Infra"
        c.setFillColor(INK)
        c.setFont("Helvetica-Bold", 12)
        c.drawString(15 * mm + lw + 4 * mm, top - 3.5 * mm, name.upper() if len(name) < 34 else name)
        right = []
        if self.s.get("address"):
            right.append(self.s["address"].replace("\n", ", ")[:90])
        line2 = "   ".join(x for x in [self.s.get("phone"), self.s.get("email")] if x)
        if line2:
            right.append(line2)
        line3 = "   ".join(x for x in [f"GSTIN {self.s['gstin']}" if self.s.get("gstin") else None,
                                        f"Licence {self.s['elb_licence']}" if self.s.get("elb_licence") else None] if x)
        if line3:
            right.append(line3)
        c.setFont("Helvetica", 7.6)
        c.setFillColor(MUTED)
        for n, t in enumerate(right):
            c.drawRightString(w - 15 * mm, top - 2.5 * mm - n * 3.6 * mm, t)
        # the tagline wraps so it never runs under the contact block on the right
        tx = 15 * mm + lw + 4 * mm
        room = w - 15 * mm - max((stringWidth(t, "Helvetica", 7.6) for t in right), default=0) - 5 * mm - tx
        tag = self.s.get("tagline") or "LT and HT electrical contracting and consulting, a Sellandiamman Group company"
        lines, cur = [], ""
        for word in tag.split():
            nxt = f"{cur} {word}".strip()
            if cur and stringWidth(nxt, "Helvetica", 7.6) > room:
                lines.append(cur)
                cur = word
            else:
                cur = nxt
        lines.append(cur)
        for n, t in enumerate(lines[:2]):
            c.drawString(tx, top - 7.5 * mm - n * 3.2 * mm, t)
        c.setStrokeColor(ACCENT)
        c.setLineWidth(1.6)
        c.line(15 * mm, top - 12.5 * mm, w - 15 * mm, top - 12.5 * mm)
        # footer
        c.setStrokeColor(LINE)
        c.setLineWidth(0.5)
        c.line(15 * mm, 13 * mm, w - 15 * mm, 13 * mm)
        c.setFont("Helvetica", 7)
        c.setFillColor(MUTED)
        c.drawString(15 * mm, 9 * mm, f"{name}, {self.s.get('website') or 'sellandiammanpowerinfra.com'}")
        c.drawRightString(w - 15 * mm, 9 * mm, f"Page {doc.page}")
        if self.watermark:
            c.setFont("Helvetica-Bold", 60)
            c.setFillColor(colors.Color(0.85, 0.87, 0.9, alpha=0.35))
            c.translate(w / 2, h / 2)
            c.rotate(35)
            c.drawCentredString(0, 0, self.watermark)
        c.restoreState()

    # ---------------------------------------------------------------- content
    def heading(self):
        self.flow.append(P(self.title, "title"))
        if self.subtitle:
            self.flow.append(P(self.subtitle, "sub"))
        self.flow.append(Spacer(1, 4 * mm))

    def h(self, text):
        self.flow.append(P(text, "h"))

    def p(self, text, style="p"):
        if text:
            self.flow.append(P(text, style))
            self.flow.append(Spacer(1, 1.5 * mm))

    def md(self, text):
        """Very small markdown: paragraphs, '- ' bullets, '**bold**' left as plain text."""
        for block in (text or "").split("\n\n"):
            lines = [ln for ln in block.splitlines() if ln.strip()]
            if not lines:
                continue
            if all(ln.lstrip().startswith(("- ", "* ")) for ln in lines):
                for ln in lines:
                    self.flow.append(Paragraph("• " + escape(ln.lstrip()[2:].replace("**", "")), S["p"]))
            else:
                self.flow.append(P(" ".join(lines).replace("**", "").lstrip("# "), "p"))
            self.flow.append(Spacer(1, 1.5 * mm))

    def meta(self, pairs, cols=2):
        pairs = [(k, v) for k, v in pairs if v not in (None, "")]
        if not pairs:
            return
        rows = []
        for i in range(0, len(pairs), cols):
            row = []
            for k, v in pairs[i:i + cols]:
                row += [P(k, "small"), P(v, "cellb")]
            while len(row) < cols * 2:
                row += ["", ""]
            rows.append(row)
        w = self.pagesize[0] - 30 * mm
        cw = [w * 0.16, w * 0.34] * cols if cols == 2 else [w * 0.25, w * 0.75]
        t = Table(rows, colWidths=cw)
        t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5), ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                               ("BACKGROUND", (0, 0), (-1, -1), WASH), ("BOX", (0, 0), (-1, -1), 0.4, LINE)]))
        self.flow.append(t)
        self.flow.append(Spacer(1, 4 * mm))

    def table(self, headers, rows, widths=None, align=None, repeat=1, zebra=True, font_small=False):
        w = self.pagesize[0] - 30 * mm
        n = len(headers)
        align = align or ["L"] * n
        if widths is None:
            widths = [w / n] * n
        else:
            tot = sum(widths)
            widths = [x * w / tot for x in widths]
        data = [[P(hd, "headr" if align[i] == "R" else "head") for i, hd in enumerate(headers)]]
        for r in rows:
            data.append([P(v, "cellr" if align[i] == "R" else "cell") if not hasattr(v, "wrap") else v for i, v in enumerate(r)])
        t = Table(data, colWidths=widths, repeatRows=repeat)
        st = [("BACKGROUND", (0, 0), (-1, 0), INK), ("VALIGN", (0, 0), (-1, -1), "TOP"),
              ("LINEBELOW", (0, 1), (-1, -1), 0.3, LINE), ("BOTTOMPADDING", (0, 0), (-1, -1), 3), ("TOPPADDING", (0, 0), (-1, -1), 3)]
        if zebra:
            for i in range(2, len(data), 2):
                st.append(("BACKGROUND", (0, i), (-1, i), WASH))
        t.setStyle(TableStyle(st))
        self.flow.append(t)
        self.flow.append(Spacer(1, 3 * mm))

    def totals(self, pairs, words=None):
        w = self.pagesize[0] - 30 * mm
        rows = []
        for k, v in pairs:
            bold = k.lower().startswith(("total", "net", "grand", "balance", "amount due"))
            rows.append([P(k, "cellb" if bold else "cell"), Paragraph(escape(rs(v)), S["cellr"] if not bold else ParagraphStyle("x", parent=S["cellr"], fontName="Helvetica-Bold"))])
        t = Table(rows, colWidths=[w * 0.25, w * 0.2], hAlign="RIGHT")
        t.setStyle(TableStyle([("LINEABOVE", (0, -1), (-1, -1), 0.8, INK), ("BOTTOMPADDING", (0, 0), (-1, -1), 2), ("TOPPADDING", (0, 0), (-1, -1), 2)]))
        self.flow.append(KeepTogether([t]))
        if words:
            self.flow.append(Spacer(1, 2 * mm))
            self.flow.append(P(words, "small"))
        self.flow.append(Spacer(1, 4 * mm))

    def signature(self, left="Prepared by", right="For Sellandiamman Power Infra"):
        w = self.pagesize[0] - 30 * mm
        t = Table([[P(left, "small"), P(right, "small")], ["", ""], [P("Signature", "small"), P("Authorised signatory", "small")]],
                  colWidths=[w / 2, w / 2], rowHeights=[None, 14 * mm, None])
        t.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "RIGHT")]))
        self.flow.append(KeepTogether([Spacer(1, 6 * mm), t]))

    def image_svgless(self, png_bytes, width_mm=60):
        img = RLImage(io.BytesIO(png_bytes), width=width_mm * mm, height=width_mm * mm)
        self.flow.append(img)

    def add(self, flowable):
        self.flow.append(flowable)

    def build(self):
        buf = io.BytesIO()
        w, h = self.pagesize
        doc = BaseDocTemplate(buf, pagesize=self.pagesize, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=32 * mm, bottomMargin=18 * mm,
                              title=self.title, author=self.s.get("company_name") or "Sellandiamman Power Infra")
        frame = Frame(15 * mm, 18 * mm, w - 30 * mm, h - 50 * mm, id="f", leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0)
        doc.addPageTemplates([PageTemplate(id="p", frames=[frame], onPage=self._page)])
        story = []
        story.append(P(self.title, "title"))
        if self.subtitle:
            story.append(P(self.subtitle, "sub"))
        story.append(Spacer(1, 4 * mm))
        doc.build(story + self.flow)
        return buf.getvalue()


def stamp():
    return datetime.now().strftime("%d %b %Y %H:%M")
